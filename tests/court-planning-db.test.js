const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const fixture = fs.readFileSync(path.join(__dirname, 'fixtures/court-booking-schema.sql'), 'utf8');
const migration = name => fs.readFileSync(path.join(__dirname, '../supabase/migrations', name), 'utf8');

test('PostgreSQL: court planning privacy, overlap rules and admin alerts', {
  skip: !process.env.PADEL_PGLITE_MODULE && 'Requires local PGlite',
}, async t => {
  const { PGlite } = await import(pathToFileURL(process.env.PADEL_PGLITE_MODULE).href);
  const db = new PGlite();
  const user = '00000000-0000-0000-0000-000000000001';
  const outsider = '00000000-0000-0000-0000-000000000002';
  try {
    await db.exec(fixture);
    await db.exec(`alter table auth.users add column email text, add column email_confirmed_at timestamptz;
      alter table public.seasons add column label text, add column is_active boolean default true, add column tournament_mode text default 'none';
      alter table public.matches add column competition_stage text default 'league';
      create table public.players (id text primary key);
      create table public.training_sessions (id bigint generated by default as identity primary key,
        played_on date, display_time time, status text, created_by uuid, player_ids text[]);
      create function private.training_session_at(date, time) returns timestamptz language sql immutable
        as $$ select ($1 + $2) at time zone 'Europe/Berlin' $$;
      create function public.schedule_training_session(date, time, text[], jsonb) returns bigint
        language sql as $$ insert into public.training_sessions (played_on, display_time, status, created_by, player_ids)
          values ($1, $2, 'scheduled', auth.uid(), $3) returning id $$;
      create function public.update_scheduled_training(bigint, date, time, text[], jsonb) returns void
        language sql as $$ update public.training_sessions set played_on=$2, display_time=$3, player_ids=$4 where id=$1 $$;`);
    for (const file of [
      '20261106190000_court_booking_workflow.sql',
      '20261107120000_booking_mail_match_assignment.sql',
      '20261111140000_training_court_bookings.sql',
      '20261113140000_auto_assign_league_court_bookings.sql',
      '20261117140000_booking_import_ignore_organizer.sql',
      '20261127160000_court_planning.sql',
      '20261127161000_court_outlook_alerts.sql',
    ]) await db.exec(migration(file));
    await db.exec(`set request.jwt.claim.sub = '${user}'; set request.jwt.claim.role = 'service_role';
      insert into auth.users values ('${user}', 'p1@example.com', now()), ('${outsider}', 'p5@example.com', now());
      insert into public.players values ('p1'), ('p2'), ('p3'), ('p4'), ('p5'), ('p6'), ('p7'), ('p8');
      insert into public.profiles values ('${user}', 'p1', 'player'), ('${outsider}', 'p5', 'admin');
      insert into public.seasons (id, results_entry_enabled, label) values ('test', true, 'Test');
      insert into public.leagues values ('test', 'liga', 'Liga');
      insert into public.matches (id, season_id, league_id, display_label, match_at) values
        ('target', 'test', 'liga', 'Partie 1', null),
        ('booked', 'test', 'liga', 'Partie 2', '2099-11-27T11:00Z'),
        ('imported', 'test', 'liga', 'Partie 3', '2099-11-27T11:45Z');
      insert into public.match_players
        select game, 'p' || n, n % 2 + 1 from unnest(array['target', 'booked', 'imported']) game cross join generate_series(1, 4) n;
      insert into private.court_bookings (provider_booking_id, court_name, organizer, starts_at, ends_at, source_occurred_at, match_id)
        values ('linked', 'H1', 'Test', '2099-11-27T11:00Z', '2099-11-27T12:30Z', now(), 'booked');`);

    const scalar = async (query, params = []) => Object.values((await db.query(query, params)).rows[0])[0];
    assert.equal(await scalar("select public.set_my_preferred_play_time('midday')"), 'midday');
    assert.equal(await scalar('select public.get_my_preferred_play_time()'), 'midday');
    assert.equal(await scalar('select public.set_my_preferred_play_time(null)'), null);
    assert.equal(await scalar('select public.get_my_preferred_play_time()'), null);
    await assert.rejects(scalar("select public.set_my_preferred_play_time('night')"), /check constraint/);
    assert.equal(await scalar(`select has_function_privilege('authenticated',
      'public.get_court_planning_subject(uuid,text,timestamptz,timestamptz)', 'execute')`), false);
    const read = id => scalar("select public.get_court_planning_subject($1, 'target', '2099-11-27T00:00Z', '2099-11-28T00:00Z')", [id]);
    assert.equal(await read(outsider), null);
    assert.equal((await read(user)).members.length, 4);

    await assert.rejects(scalar("select public.schedule_match('target', '2099-11-27 13:00')"), /überschneidet/);
    assert.equal(await scalar("select match_at from public.matches where id='target'"), null);
    await assert.rejects(scalar("select public.schedule_training_session('2099-11-27', '13:00', array['p1','p5','p6','p7'], '{}')"), /überschneidet/);
    const session = await scalar("select public.schedule_training_session('2099-11-27', '14:00', array['p1','p5','p6','p7'], '{}')");
    assert.equal(await scalar('select count(*)::integer from public.training_sessions'), 1);
    await assert.rejects(scalar("select public.update_scheduled_training($1, '2099-11-27', '12:30', array['p1','p5','p6','p7'], '{}')", [session]), /überschneidet/);
    const imported = await scalar(`select public.record_court_booking_with_match(
      'mail-while-overlapping', null, 'H2', 'Headsquare United', '2099-11-27T11:30Z', '2099-11-27T12:30Z',
      false, '2099-11-26T10:00Z', 1, null, null, null)`);
    assert.equal(imported.matchId, 'imported', 'automatic mail assignment keeps its existing behavior');
    await t.test('Outlook alert is admin-only, deduplicated across parties, and ends on recovery', async () => {
      const lease = '00000000-0000-0000-0000-000000000010';
      const secondLease = '00000000-0000-0000-0000-000000000011';
      const unconfirmed = '00000000-0000-0000-0000-000000000003';
      await db.exec(`insert into auth.users values ('${unconfirmed}', 'private@example.com', null);
        insert into public.profiles values ('${unconfirmed}', 'p6', 'admin');`);
      const readHealth = () => scalar('select public.get_my_court_outlook_health()');
      const report = (match, minute, status) => scalar('select public.record_court_outlook_health($1, $2, $3)',
        [match, `2099-11-27T08:${minute}:00Z`, status]);
      const claim = async token => (await db.query('select * from public.claim_court_outlook_alerts($1)', [token])).rows;
      const current = (incident, token) => scalar('select public.court_outlook_alert_is_current($1, $2, $3)', [incident, outsider, token]);

      await assert.rejects(readHealth(), /bestätigte Admin-Konten/);
      assert.equal(await scalar(`select has_function_privilege('authenticated',
        'public.record_court_outlook_health(text,timestamptz,text)', 'execute')`), false);
      assert.equal(await scalar(`select has_function_privilege('authenticated',
        'public.claim_court_outlook_alerts(uuid,integer)', 'execute')`), false);
      await db.exec(`set request.jwt.claim.sub = '${outsider}'`);
      await report('target', '01', 'not_configured');
      assert.equal(await readHealth(), null);
      assert.deepEqual(await claim(lease), []);

      await report('target', '02', 'calendar_unavailable');
      await report('booked', '03', 'ready');
      await report('imported', '04', 'calendar_unavailable');
      await report('target', '05', 'calendar_unavailable');
      assert.equal(await readHealth(), 'calendar_unavailable');
      const [job, ...extra] = await claim(lease);
      assert.equal(extra.length, 0, 'only confirmed admins get one queued mail');
      assert.equal(job.user_id, outsider);
      assert.equal(job.reason, 'calendar_unavailable');
      assert.equal(job.idempotency_key, `court-outlook-${job.incident_id}-${outsider}`);
      assert.equal(await current(job.incident_id, lease), true);
      assert.deepEqual(await claim(secondLease), []);
      await scalar('select public.complete_court_outlook_alert($1, $2, $3, true)', [job.incident_id, outsider, lease]);

      await report('target', '06', 'ready');
      assert.equal(await readHealth(), 'calendar_unavailable', 'the other failed party remains active');
      assert.deepEqual(await claim(lease), []);
      await report('imported', '07', 'ready');
      assert.equal(await readHealth(), null);
      await report('imported', '06', 'calendar_unavailable');
      assert.equal(await readHealth(), null, 'older responses cannot reopen a recovered warning');

      await report('target', '08', 'reconnect');
      const [newJob] = await claim(secondLease);
      assert.notEqual(newJob.incident_id, job.incident_id);
      assert.equal(newJob.reason, 'reconnect');
      await report('booked', '09', 'ready');
      assert.equal(await current(newJob.incident_id, secondLease), false, 'recovery cancels pending delivery');
      assert.equal(await readHealth(), null);
    });
  } finally {
    await db.close();
  }
});
